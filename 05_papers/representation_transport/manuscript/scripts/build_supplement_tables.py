UNI = {"\u2192": r"$\rightarrow$", "\u2265": r"$\geq$", "\u2264": r"$\leq$", "\u00d7": r"$\times$", "\u2013": "--", "\u2014": "---",
       "\u2019": "'", "\u2018": "`", "\u201c": "``", "\u201d": "''", "\u2248": r"$\approx$", "\u00b1": r"$\pm$", "\u2026": r"\ldots{}",
       "\u00a7": r"\S{}", "\u2260": r"$\neq$", "\u2212": "-", "\u00a0": "~"}


def tx(s):
    s = str(s)
    for a, b in DISPLAY_SUBST:
        s = s.replace(a, b)
    s = s.replace("\\", "\x00")
    for a, b in (("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"),
                 ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"), ("<", r"\textless{}"), (">", r"\textgreater{}")):
        s = s.replace(a, b)
    s = s.replace("\x00", r"\textbackslash{}")
    for a, b in UNI.items():
        s = s.replace(a, b)
    s = re.sub(r"(?<=[A-Za-z0-9])-(?=[A-Za-z0-9])", r"-\\allowbreak{}", s)
    s = s.replace(r"\_", r"\_\allowbreak{}").replace("/", r"/\allowbreak{}").replace(";", r";\allowbreak{}")
    bad = [c for c in s if ord(c) > 255]
    if bad:
        raise SystemExit(f"untypeset character(s) {bad!r} in: {s[:60]}")
    return s


def ids(s):
    """Identifier lists (C-SG03-01;C-SG03-02) wrap at the separators."""
    return r"\texttt{" + tx(s).replace(";", r";\allowbreak{} ") + "}"


def widths(spec):
    """p{a\\textwidth} -> ragged p{a\\linewidth - 2\\tabcolsep}: the fractions then sum to at most the line width."""
    spec = re.sub(r"(?<!\\arraybackslash\})p\{", r">{\\raggedright\\arraybackslash}p{", spec)
    return re.sub(r"p\{([\d.]+)\\textwidth\}", r"p{\\dimexpr \1\\linewidth-2\\tabcolsep\\relax}", spec)


def longtable(spec, head, rows, caption, label, size=r"\footnotesize", note=""):
    out = [f"% generated by scripts/build_supplement_tables.py -- do not edit ({label})", size, r"\setlength{\tabcolsep}{3pt}",
           r"\begin{longtable}{" + widths(spec) + "}", r"\caption{" + caption + r"}\label{" + label + r"}\\", r"\toprule",
           " & ".join(head) + r" \\", r"\midrule", r"\endfirsthead", r"\multicolumn{" + str(len(head)) + r"}{@{}l}{\emph{(continued)}}\\",
           r"\toprule", " & ".join(head) + r" \\", r"\midrule", r"\endhead", r"\bottomrule", r"\endfoot"]
    out += [" & ".join(r) + r" \\" for r in rows]
    out += [r"\end{longtable}"]
    if note:
        out += [r"\vspace{-0.6\baselineskip}", r"{\scriptsize " + note + r"\par}"]
    out += [r"\normalsize", ""]
    return "\n".join(out)


