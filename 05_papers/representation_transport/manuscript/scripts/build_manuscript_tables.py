#!/usr/bin/env python3
"""D047: deterministic LaTeX tables and v1 numeric claims from frozen authorities (no hand-typed numbers).

Outputs:
  generated/table1.tex             evidence universe and frame status (main)
  generated/table2.tex             support geometry by dimension, no T-label column (main)
  supplement/table_s3_near_miss.tex  former main Table 3 (supplement)
  revision_v1/V1_NUMERIC_CLAIMS.csv  new claim rows needed by v1 (frame verification composition)
Run: python3 -I scripts/build_manuscript_tables.py [--check]
"""
import csv
import io
import os
import sys

MS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RT = os.path.dirname(MS)
FIN = os.path.join(RT, "final_scope_c")
MAN = os.path.join(RT, "evidence_universe", "layer_a_reconciliation", "RECONCILED_LAYER_A_MANIFEST.csv")
rd = lambda p: list(csv.DictReader(open(p, newline="", encoding="utf-8")))
DIMS = [("MAGNITUDE_B2", "Transfer magnitude"), ("WITHDRAWAL", "Withdrawal schedule"), ("CONDITIONALITY", "Conditionality"),
        ("CADENCE", "Payment cadence"), ("DURATION", "Promised duration"), ("BASELINE_EMPLOYMENT", "Baseline employment (state)")]
STATUS_ORDER = ["VERIFIED", "PENDING", "FRAME-CONFLICT"]


def composition():
    c = {}
    for r in rd(MAN):
        if r["denominator_member"] == "YES":
            c[r["verification_status"]] = c.get(r["verification_status"], 0) + 1
    return c


def table1():
    fin = {r["architecture_dimension"]: r for r in rd(os.path.join(FIN, "SCOPE_C_FINAL_SUPPORT_GEOMETRY.csv"))}["WITHDRAWAL"]
    comp = composition()
    names = sorted({r["experiment_name"] for r in rd(os.path.join(FIN, "LAYER_B_SUPPORT_AUDIT.csv"))})
    tex = r"""%% generated by scripts/build_manuscript_tables.py from SCOPE_C_FINAL_SUPPORT_GEOMETRY.csv, LAYER_B_SUPPORT_AUDIT.csv and RECONCILED_LAYER_A_MANIFEST.csv -- do not edit
\begin{table}[t]
\centering
\caption{Evidence universe. The two layers have different roles and are never pooled into a common denominator.}
\label{tab:universe}
\small
\begin{tabular}{@{}p{0.18\textwidth}p{0.37\textwidth}p{0.37\textwidth}@{}}
\toprule
 & Layer A & Layer B \\
\midrule
Definition & Census of a frozen, frame-defined set of modern basic-income, guaranteed-income and closely related randomised experiments with employment outcomes & Audited set of historical and adjacent designs with documented variation in programme design, frozen before extraction \\
Members & %(A)s experiments (frame status: %(comp)s; all retained) & %(B)s design cases \\
Status & Census of the frame (denominator for prevalence statements) & Audit (not a census; no prevalence is estimated) \\
Role & Census of where design support is lost; selection audit & Additional comparisons, especially isolated historical designs \\
Unit of independence & Transport family (independent identification source) & Transport family \\
\bottomrule
\end{tabular}

\smallskip
\parbox{\linewidth}{\footnotesize Layer B members: %(names)s. Outcome domain: employment; prospectively specified target: individual probability of being employed or working.}
\end{table}
""" % dict(A=fin["layer_a_census_denominator"], B=fin["layer_b_audited_members"],
           comp="; ".join(f"{comp.get(s, 0)} {s.lower().replace('-', ' ')}" for s in STATUS_ORDER), names="; ".join(names).replace("&", r"\&"))
    return tex


def table2():
    fin = {r["architecture_dimension"]: r for r in rd(os.path.join(FIN, "SCOPE_C_FINAL_SUPPORT_GEOMETRY.csv"))}
    q = lambda r, p: "/".join(r[f"{p}_{c}"] for c in ("with_variation", "isolated", "isolated_EA", "isolated_EA_usableU"))
    stage = {"V": "variation", "I": "isolation", "E": "estimand", "U": "uncertainty"}
    rows = []
    for d, lab in DIMS:
        r = fin[d]
        strict = len([x for x in r["strict_families"].split(";") if x and x != "NONE"])
        rows.append(f"{lab} & {q(r, 'layer_a_families')} & {q(r, 'layer_b_audited_families')} & {q(r, 'scope_c_union_families')} & "
                    f"{r['scope_c_union_families_between_study_EA_usableU']} & {strict} & {r['scope_c_union_families_isolated_EXTENSIVE_usableU']} & "
                    f"{stage[r['primary_blocker'].split(':')[0].split(' ')[0]]} \\\\")
    return r"""% generated by scripts/build_manuscript_tables.py from SCOPE_C_FINAL_SUPPORT_GEOMETRY.csv -- do not edit
\begin{table}[t]
\centering
\caption{Support geometry by dimension. Entries are counts of transport families (independent identification sources) that vary the feature / isolate it / also report a compatible employment estimand / also report usable uncertainty (standard error or confidence interval).}
\label{tab:geometry}
\footnotesize
\setlength{\tabcolsep}{3.5pt}
\resizebox{\textwidth}{!}{%
\begin{tabular}{@{}lccccccl@{}}
\toprule
Dimension & Layer A census & Layer B audit & Support union & Between-study & Independent & Broader (E-B) & Support \\
 & (of 43) & (9 cases) & (not prevalence) & strict support & strict sources & isolated + U & stops at \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}}

\smallskip
\parbox{\linewidth}{\footnotesize Layer A columns are census counts for the frame; the support union combines Layer A cells with Layer B audit paths and is not a prevalence. Magnitude, duration and baseline employment vary almost only between studies and are never isolated; their between-study support is shown separately. ``Broader (E-B)'' admits extensive-margin objects such as hours- or earnings-threshold employment; it is a sensitivity view, not the prospectively specified target. ``Support stops at'' is the stage at which the union loses support.}
\end{table}
"""


CASES = [("WITHDRAWAL", "X007"), ("WITHDRAWAL", "X002"), ("WITHDRAWAL", "X001"), ("WITHDRAWAL", "X004"), ("WITHDRAWAL", "X057"), ("WITHDRAWAL", "X003"),
         ("CONDITIONALITY", "X060"), ("CONDITIONALITY", "X066"), ("CONDITIONALITY", "X057"), ("CONDITIONALITY", "X067"),
         ("CADENCE", "X016"), ("CADENCE", "X068"), ("CADENCE", "X045")]
LABEL = {"X007": "B-MINCOME", "X002": "RIME", "X001": "New Jersey-Pennsylvania NIT", "X004": "Gary NIT", "X057": "Wageningen", "X003": "Seattle-Denver NIT (Denver)",
         "X060": "Utrecht", "X066": "Vermont WRP", "X067": "Minnesota MFIP", "X016": "Compton Pledge", "X068": "Nigeria FNLP cash", "X045": "Newark"}


def table_s3():
    stage = {"NONE": "variation", "V": "isolation", "I": "estimand", "E": "uncertainty"}
    out = []
    for d, e in CASES:
        r = [x for x in rd(os.path.join(FIN, f"{d}_SUPPORT_PATHS_FINAL.csv")) if x["experiment_id"] == e and x["cell_representative"] == "YES"][0]
        stop = "passes" if r["failure_reason"] == "STRICT PASS" else stage[r["strict_gate_stage_reached"]]
        out.append(f"{d.title()} & {LABEL[e]} & {r['I']} & {r['E']} & {r['U']} & {stop} \\\\")
    return r"""% generated by scripts/build_manuscript_tables.py from final_scope_c/*_SUPPORT_PATHS_FINAL.csv -- do not edit (Supplementary Table S3)
\begin{tabular}{@{}llllll@{}}
\toprule
Dimension & Design & Isolation & Estimand & Uncertainty & Stops at \\
\midrule
""" + "\n".join(out) + r"""
\bottomrule
\end{tabular}
"""


def v1_claims():
    comp = composition()
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=["claim_id", "quantity", "value", "authoritative_input", "script"], lineterminator="\n")
    w.writeheader()
    w.writerow(dict(claim_id="F-01", quantity="Layer A frame verification composition (VERIFIED; PENDING; FRAME-CONFLICT)",
                    value="; ".join(str(comp.get(s, 0)) for s in STATUS_ORDER),
                    authoritative_input="evidence_universe/layer_a_reconciliation/RECONCILED_LAYER_A_MANIFEST.csv", script="manuscript/scripts/build_manuscript_tables.py"))
    return buf.getvalue()


OUTPUTS = {"generated/table1.tex": table1, "generated/table2.tex": table2, "supplement/table_s3_near_miss.tex": table_s3, "revision_v1/V1_NUMERIC_CLAIMS.csv": v1_claims}

if __name__ == "__main__":
    bad = []
    for rel, f in OUTPUTS.items():
        p, t = os.path.join(MS, rel), f()
        if "--check" in sys.argv:
            if not os.path.exists(p) or open(p, encoding="utf-8").read() != t:
                bad.append(rel)
        else:
            if not os.path.exists(p) or open(p, encoding="utf-8").read() != t:  # D048A: write only on change
                open(p, "w", encoding="utf-8").write(t)
    print(("differ: " + str(bad)) if bad else ("tables current" if "--check" in sys.argv else "written"))
    sys.exit(1 if bad else 0)
